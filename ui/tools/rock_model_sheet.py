#!/usr/bin/env python3
"""
Renders the mountain rocks from the "Stylised Rocks Asset Pack" (Sketchfab download, not kept in the repo — pass the
download folder) into public/sprites/rocks.png: one row per material (ROW_MATERIALS: plain, mossy, snowy, desert) by
one column per piece (PIECES: the 14 rock groups, then 8 tall single rocks), CELL px each, all seen from the same
fixed angle as the tank sheets (tools/tank_model_sheet.py), ground point at PIVOT. Also writes
src/render/RockSheetData.ts: per piece, its half-width on the ground and its height (sheet px), for placing it.
Usage: python -I tools/rock_model_sheet.py <download folder> [--preview out.png]   (run from ui/)
"""
import math
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aircraft_model_sheet as am  # noqa: E402
import tank_model_sheet as tm  # noqa: E402

CELL = 160
tm.CELL = CELL
tm.PIVOT = (CELL // 2, int(CELL * 0.78))
ROW_MATERIALS = ('Plain', 'Mossy', 'Snowy', 'Desert')
PIECES = [f'Rock_Group{k}' for k in range(1, 15)] + [f'Rock{k}' for k in (1, 2, 3, 5, 6, 7, 8, 9)]
HEADING = 0.6  # radians: every piece seen from the same side (the light comes from the upper left like the tanks)
FIT_W = CELL * 0.92
FIT_H = CELL * 0.74


def piece_mask(objs, mat, piece):
    want = f'{mat}_{piece}_'
    alt = f'{mat}{piece}_'  # 'SnowyRock14_77'
    return np.array([str(o).startswith(want) or str(o).startswith(alt) for o in objs])


def main():
    folder = sys.argv[1]
    cfg = dict(src='source/Stylised_Rock_Collection.fbx',
               force_textures={f'M_{m}_Rock': f'textures/M_{m}_Rock_BaseColour.png' for m in ROW_MATERIALS})
    v, vt, tris, uvs, mats, objs, textures, kd = am.load(folder, cfg)
    for m, t in cfg['force_textures'].items():
        textures[m] = os.path.join(folder, t)
    sheet = Image.new('RGBA', (CELL * len(PIECES), CELL * len(ROW_MATERIALS)))
    meta = []
    for col, piece in enumerate(PIECES):
        # Size from the plain copy: every material row of a piece is drawn at the same scale.
        base = piece_mask(objs, 'Plain', piece)
        p = v[np.unique(tris[base])]
        lo, hi = p.min(0), p.max(0)
        half = max(hi[0] - lo[0], hi[2] - lo[2]) / 2
        height = hi[1] - lo[1]
        scale = min(FIT_W / (2 * half * 1.05), FIT_H / (height * tm.COS_E + half * tm.SIN_E))
        meta.append((round(half * scale, 1), round(height * scale * tm.COS_E, 1)))
        for row, mat in enumerate(ROW_MATERIALS):
            sel = piece_mask(objs, mat, piece)
            if not sel.any():
                continue
            q = v[np.unique(tris[sel])]
            qlo, qhi = q.min(0), q.max(0)
            mid = (qlo + qhi) / 2
            model = np.stack([v[:, 0] - mid[0], v[:, 2] - mid[2], v[:, 1] - qlo[1]], 1)
            pos, colr, nrm, _ = tm.sample(model, vt, tris[sel], uvs[sel], mats[sel], textures, kd, (scale * tm.SS * 1.6) ** 2, (128, 128, 128))
            sheet.alpha_composite(tm.render(pos, colr, nrm, HEADING, scale, True), (col * CELL, row * CELL))
    if '--preview' in sys.argv:
        sheet.save(sys.argv[sys.argv.index('--preview') + 1])
        return
    sheet.save('public/sprites/rocks.png', optimize=True)
    with open('src/render/RockSheetData.ts', 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/rock_model_sheet.py: per piece (sheet column), [half-width on the ground, height] in sheet px.\n')
        f.write(f'export const ROCK_CELL = {CELL};\nexport const ROCK_PIVOT = [{tm.PIVOT[0]}, {tm.PIVOT[1]}] as const;\n')
        f.write(f'/** Columns 0–13: rock groups (massifs); 14–21: single rocks. Rows: {", ".join(ROW_MATERIALS).lower()}. */\n')
        f.write('export const ROCK_PIECES: readonly (readonly [number, number])[] = [\n')
        for h, t in meta:
            f.write(f'  [{h}, {t}],\n')
        f.write('];\n')


if __name__ == '__main__':
    main()
