"""Sort ui/public/sprites into one folder per nation, and write the lookup the game loads sprites through.

    python tools/organize_sprites.py      # also run at the end of tools/to_webp.py

Rules (file names stay the same, only their folder changes):
- A sprite whose name carries a nation (usa / us, russia / ru, china / cn, europe / eu, islamic) goes under that nation:
  <nation>/<group>/<file> when the nation has several sprites of that group (radar + its antenna frames, the wall
  pieces, the soldier sheets of one kind, a truck's body + chassis...), or straight in <nation>/<file> when it is the
  only one.
- The group is the name before the nation (without "building-"), e.g. building-radar-usa-ant03 -> radar,
  building-wall-china-3-1 -> wall, truck-hemtt-usa-body -> truck-hemtt; for soldier sheets named <nation>-<kind>-...
  it is the kind (us-regular-8dir -> regular).
- The other nations' capitals (building-nation-<country>) go under capitals/<country>/ the same way.
- Sprites of no nation (effects, trees, shared sheets) stay at the sprites root.
Blender / Pillow tools keep writing their PNGs at the sprites root; this script moves them (and their .webp) into
place and rewrites ui/src/render/spriteManifest.ts (base name -> folder), which spriteUrl() reads.
"""
import shutil
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "ui" / "public" / "sprites"
MANIFEST = Path(__file__).resolve().parent.parent / "ui" / "src" / "render" / "spriteManifest.ts"
NATIONS = {"usa": "usa", "us": "usa", "russia": "russia", "ru": "russia", "china": "china", "cn": "china", "europe": "europe", "eu": "europe", "islamic": "islamic"}
EXTS = {".png", ".webp"}


def classify(base: str):
    """(nation, group) for a sprite base name, or None when it belongs to no nation."""
    parts = base.split("-")
    # Capitals of the other (neutral) nations: sprites/capitals/<country>/[<group>/].
    if base.startswith("building-nation-") and len(parts) >= 3:
        return f"capitals/{parts[2]}", "nation"
    for i, p in enumerate(parts):
        if p in NATIONS:
            nation = NATIONS[p]
            prefix = [x for x in parts[:i] if x != "building"]
            if prefix:
                group = "-".join(prefix)
            elif i + 1 < len(parts):
                group = parts[i + 1]
            else:
                group = base
            return nation, group
    return None


def main():
    files = defaultdict(list)  # base name -> current paths
    for p in ROOT.rglob("*"):
        if p.is_file() and p.suffix.lower() in EXTS:
            files[p.stem].append(p)
    groups = defaultdict(set)  # (nation, group) -> base names
    for base in files:
        c = classify(base)
        if c:
            groups[c].add(base)
    target = {}
    for (nation, group), bases in groups.items():
        for base in bases:
            target[base] = f"{nation}/{group}" if len(bases) > 1 else nation
    moved = 0
    for base, paths in files.items():
        folder = ROOT / target[base] if base in target else ROOT
        for p in paths:
            dest = folder / p.name
            if p.resolve() != dest.resolve():
                folder.mkdir(parents=True, exist_ok=True)
                if dest.exists():
                    dest.unlink()  # a fresh render at the root replaces the old copy
                shutil.move(str(p), str(dest))
                moved += 1
    # Drop folders left empty.
    for d in sorted((d for d in ROOT.rglob("*") if d.is_dir()), key=lambda d: len(d.parts), reverse=True):
        if not any(d.iterdir()):
            d.rmdir()
    lines = [
        "/**",
        " * Folder of each nation's sprite under public/sprites (base name -> folder). GENERATED by tools/organize_sprites.py:",
        " * do not edit by hand. Sprites not listed sit at the sprites root.",
        " */",
        "export const SPRITE_FOLDERS: Readonly<Record<string, string>> = {",
    ]
    for base in sorted(target):
        lines.append(f"  '{base}': '{target[base]}',")
    lines.append("};")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"organize_sprites: {moved} files moved, {len(target)} nation sprites in {len(groups)} groups")


if __name__ == "__main__":
    main()
